/** Local, isolated rehearsal only. NOT a Supabase migration or live importer.
 * This journal deliberately has no production SQL installer or public RPC. */
import type {PGlite} from '@electric-sql/pglite';
import {canonical, digest, type Json, type MigrationManifest} from '../lib/native-migration';
export type RehearsalTarget = {organizationId: string; clientId: string; actorId: string};
function targetKey(target: RehearsalTarget) {
 for (const value of Object.values(target)) if (!/^[a-z0-9][a-z0-9_-]{7,79}$/.test(value)) throw Error('Destino fictício explícito inválido.');
 return JSON.stringify([target.organizationId,target.clientId]);
}
export async function initializeRehearsal(db: PGlite) {
 await db.exec(`create table rehearsal_sources(target text not null,source text not null,snapshot text not null,receipt jsonb not null,primary key(target,source));
 create table rehearsal_records(target text not null,source text not null,id text not null,payload jsonb not null,primary key(target,source,id));`);
}
/** Input is generated by the trusted preview, then integrity rechecked. It is NOT
 * an authorization boundary. No browser/user-facing route calls this function. */
export async function rehearseMigration(db: PGlite, manifest: MigrationManifest, target: RehearsalTarget, failAfter?: number) {
 const key = targetKey(target);
 if (!manifest.records.length || manifest.records.length>5000 || !/^[a-z0-9][a-z0-9_-]{7,79}$/.test(manifest.sourceNamespace)) throw Error('Inventário vazio ou inválido.');
 for (const r of manifest.records) if (r.fingerprint!==await digest({category:r.category,origin:r.origin,raw:r.raw})) throw Error('Integridade do registo inválida.');
 if (manifest.snapshot!==await digest(manifest.records as unknown as Json)) throw Error('Integridade do inventário inválida.');
 const result = await db.transaction(async tx => {
  const previous = await tx.query<{snapshot:string;receipt:Json}>('select snapshot,receipt from rehearsal_sources where target=$1 and source=$2',[key,manifest.sourceNamespace]);
  if (previous.rows.length) {
   if (previous.rows[0].snapshot!==manifest.snapshot) throw Error('A origem já tem um snapshot diferente. Nenhum registo foi alterado; é necessária reconciliação explícita.');
   return {replayed:true,receipt:previous.rows[0].receipt};
  }
  let inserted = 0;
  for (const r of manifest.records) {
   await tx.query('insert into rehearsal_records values($1,$2,$3,$4)',[key,manifest.sourceNamespace,r.id,canonical(r as unknown as Json)]);
   if (++inserted===failAfter) throw Error('Falha tardia simulada.');
  }
  const receipt = {snapshot:manifest.snapshot,organizationId:target.organizationId,clientId:target.clientId,actorId:target.actorId,
   sourceNamespace:manifest.sourceNamespace,total:inserted,prepared:manifest.records.filter(r=>r.disposition==='prepared').length,pending:manifest.records.filter(r=>r.disposition==='pending').length};
  await tx.query('insert into rehearsal_sources values($1,$2,$3,$4)',[key,manifest.sourceNamespace,manifest.snapshot,JSON.stringify(receipt)]);
  return {replayed:false,receipt};
 });
 return result;
}
